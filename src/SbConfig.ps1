<#
    SbConfig.ps1 - loading, validating and saving the SecretBeans configuration.

    The configuration is a PowerShell data file (.psd1). It is deliberately the only
    place that knows anything institution-specific: which downloaded file belongs to
    which account, and what that account is called in the ledger.

    Nothing about a CSV's *shape* belongs here. The matching .rules file already
    declares its columns, date format and account1 line, which is what makes this
    tool work with an institution it has never seen.
#>

Set-StrictMode -Version 2.0

function New-SbDefaultConfig {
    <#  A configuration skeleton, used when someone starts from nothing.  #>
    return @{
        LedgerRoot   = ''
        Currency     = '$'
        OpeningEquity= 'equity:opening balances'
        ReviewAccount= 'expenses:review'
        Accounts     = @()
    }
}

function Import-SbConfig {
    param([Parameter(Mandatory)][string]$Path)

    if (-not (Test-Path -LiteralPath $Path)) {
        throw "Configuration not found: $Path"
    }
    $cfg = Import-PowerShellDataFile -LiteralPath $Path
    $issues = @(Test-SbConfig -Config $cfg)
    if ($issues.Count -gt 0) {
        throw ("Configuration at {0} is not usable:{1}{2}" -f $Path, [Environment]::NewLine, ($issues -join [Environment]::NewLine))
    }
    return $cfg
}

function Test-SbConfig {
    <#  Returns a list of human-readable problems. Empty list means the config is usable.  #>
    param([Parameter(Mandatory)]$Config)

    $issues = New-Object System.Collections.Generic.List[string]

    if (-not $Config.ContainsKey('Accounts')) {
        $issues.Add("  - no 'Accounts' section")
        return $issues
    }
    if ($Config.Accounts.Count -eq 0) {
        $issues.Add("  - 'Accounts' is empty; add at least one account")
    }

    $seenName  = @{}
    $seenMatch = @{}
    $i = 0
    foreach ($a in $Config.Accounts) {
        $i++
        $label = "  - account #$i"
        foreach ($key in 'Name','Match','Account','Type') {
            if (-not $a.ContainsKey($key) -or [string]::IsNullOrWhiteSpace([string]$a[$key])) {
                $issues.Add("$label is missing '$key'")
            }
        }
        if ($a.ContainsKey('Name') -and -not [string]::IsNullOrWhiteSpace([string]$a.Name)) {
            $label = "  - account '$($a.Name)'"
            if ($a.Name -notmatch '^[A-Za-z0-9._-]+$') {
                $issues.Add("${label}: Name may only contain letters, digits, dot, dash and underscore (it becomes a file name)")
            }
            if ($seenName.ContainsKey($a.Name)) { $issues.Add("${label}: duplicate Name") }
            $seenName[$a.Name] = $true
        }
        if ($a.ContainsKey('Match') -and -not [string]::IsNullOrWhiteSpace([string]$a.Match)) {
            if ($seenMatch.ContainsKey($a.Match)) { $issues.Add("${label}: duplicate Match pattern '$($a.Match)'") }
            $seenMatch[$a.Match] = $true
        }
        if ($a.ContainsKey('Account') -and $a.Account -notmatch '^[a-z]') {
            $issues.Add("${label}: Account should start with a top-level ledger account in lower case, e.g. 'assets:' or 'liabilities:'")
        }
        if ($a.ContainsKey('OpeningBalance') -and $a.OpeningBalance -ne $null -and $a.OpeningBalance -ne '') {
            $parsed = 0.0
            if (-not [double]::TryParse([string]$a.OpeningBalance, [ref]$parsed)) {
                $issues.Add("${label}: OpeningBalance '$($a.OpeningBalance)' is not a number")
            }
        }
    }
    return $issues
}

function Export-SbConfig {
    <#  Writes the config back as a .psd1 that a human can still read and edit.  #>
    param(
        [Parameter(Mandatory)]$Config,
        [Parameter(Mandatory)][string]$Path
    )

    $nl = [Environment]::NewLine
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.Append("# SecretBeans configuration$nl")
    [void]$sb.Append("# Regenerated by SecretBeans. Comments you add above this line are not preserved.$nl$nl")
    [void]$sb.Append("@{$nl")
    foreach ($k in 'LedgerRoot','Currency','OpeningEquity','ReviewAccount') {
        $v = ''
        if ($Config.ContainsKey($k)) { $v = [string]$Config[$k] }
        [void]$sb.Append(("    {0,-14}= '{1}'$nl" -f $k, ($v -replace "'","''")))
    }
    [void]$sb.Append("$nl    Accounts = @($nl")
    foreach ($a in $Config.Accounts) {
        [void]$sb.Append("        @{$nl")
        foreach ($k in 'Name','Match','Account','Type','Rules','OpeningBalance','Note') {
            if (-not $a.ContainsKey($k)) { continue }
            $val = $a[$k]
            if ($null -eq $val -or ([string]$val) -eq '') { continue }
            if ($k -eq 'OpeningBalance') {
                [void]$sb.Append(("            {0,-15}= {1}$nl" -f $k, $val))
            } else {
                [void]$sb.Append(("            {0,-15}= '{1}'$nl" -f $k, ([string]$val -replace "'","''")))
            }
        }
        [void]$sb.Append("        }$nl")
    }
    [void]$sb.Append("    )$nl}$nl")

    Write-SbTextFile -Path $Path -Text $sb.ToString()
}

function Write-SbTextFile {
    <#
        Writes UTF-8 without a byte-order mark.

        Windows PowerShell 5.1's -Encoding UTF8 emits a BOM, which shows up as stray
        characters in journals and rules files and breaks a leading 'include' line.
    #>
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][AllowEmptyString()][string]$Text
    )
    $dir = Split-Path -Parent $Path
    if ($dir -and -not (Test-Path -LiteralPath $dir)) {
        New-Item -ItemType Directory -Path $dir -Force | Out-Null
    }
    $utf8NoBom = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($Path, $Text, $utf8NoBom)
}

<#
    SbJournal.ps1 - generating the supporting journal files, and reporting on the result.

    Two files are derived rather than written by hand:

      opening.journal   opening balances, so a 24-month window still shows real
                        account balances instead of starting everything at zero
      accounts.journal  account declarations, so 'hledger check accounts' passes

    Get-SbDiagnostics is what the GUI shows you before you accept a build: what is
    still uncategorised, what is waiting for review, and anything that looks like the
    same transaction imported twice from two different statements.
#>

Set-StrictMode -Version 2.0

function Get-SbTransactions {
    <#  Parse a journal into transactions. Deliberately small - hledger has already validated it.  #>
    param([Parameter(Mandatory)][string]$Path)

    $txns = New-Object System.Collections.Generic.List[object]
    if (-not (Test-Path -LiteralPath $Path)) { return $txns }

    $cur = $null
    $source = ''
    foreach ($line in [System.IO.File]::ReadAllLines($Path)) {
        # the rebuild writes a marker before each account's block
        if ($line -match '^;\s*----\s*(\S+)\s*\(') { $source = $Matches[1]; continue }
        if ($line -match '^(\d{4}-\d{2}-\d{2})\s*(.*)$') {
            $cur = [pscustomobject]@{
                Date = [datetime]::ParseExact($Matches[1], 'yyyy-MM-dd', $null)
                Description = $Matches[2].Trim()
                Source = $source
                Postings = New-Object System.Collections.Generic.List[object]
            }
            $txns.Add($cur)
        }
        elseif ($cur -and $line -match '^\s+(\S.*?)(?:\s{2,}|\t)\s*(-?[^\s].*)$') {
            $acct = $Matches[1].Trim()
            $raw  = $Matches[2].Trim()
            if ($acct.StartsWith(';')) { continue }
            $num = 0.0
            $clean = ($raw -replace '[^\d\.\-]', '')
            [void][double]::TryParse($clean, [ref]$num)
            $cur.Postings.Add([pscustomobject]@{ Account = $acct; Amount = $num })
        }
        elseif ($cur -and $line -match '^\s+(\S+)\s*$') {
            $a = $Matches[1].Trim()
            if (-not $a.StartsWith(';')) { $cur.Postings.Add([pscustomobject]@{ Account = $a; Amount = $null }) }
        }
        elseif ([string]::IsNullOrWhiteSpace($line)) { $cur = $null }
    }
    return $txns
}

function New-SbOpeningJournal {
    <#
        Opening balances, dated the day before the first transaction in the window.

        Institutions only let you download a couple of years, so the earliest CSV row
        is not the account's beginning. Without this, every balance is wrong by
        whatever the account held on day one. The figures come from the configuration,
        where you enter them from a statement.
    #>
    param(
        [Parameter(Mandatory)]$Config,
        [Parameter(Mandatory)]$Period,
        [Parameter(Mandatory)][string]$Generated
    )

    $nl   = [Environment]::NewLine
    $txns = Get-SbTransactions -Path $Generated
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("; Generated by SecretBeans - do not edit.")
    $lines.Add("; Opening balances as entered in the SecretBeans window, taken from your statements.")
    $lines.Add("; They are dated the day before the first transaction, so the 24-month window")
    $lines.Add("; still reports true balances instead of starting from zero.")
    $lines.Add("")

    $withBalance = @($Config.Accounts | Where-Object {
        $_.ContainsKey('OpeningBalance') -and $null -ne $_.OpeningBalance -and "$($_.OpeningBalance)" -ne ''
    })
    if ($withBalance.Count -eq 0 -or $txns.Count -eq 0) {
        $lines.Add("; (no opening balances entered)")
        return ($lines -join $nl) + $nl
    }

    $first = ($txns | Sort-Object Date | Select-Object -First 1).Date.AddDays(-1)
    $cur = '$'
    if ($Config.ContainsKey('Currency') -and $Config.Currency) { $cur = $Config.Currency }
    $eq = 'equity:opening balances'
    if ($Config.ContainsKey('OpeningEquity') -and $Config.OpeningEquity) { $eq = $Config.OpeningEquity }

    $lines.Add(('{0:yyyy-MM-dd} opening balances' -f $first))
    foreach ($a in $withBalance) {
        $amt = [double]$a.OpeningBalance
        # Invariant culture on purpose: {0:N2} would follow the machine's locale and
        # write 2.000,00 on a German Windows, which hledger cannot read.
        $text = $amt.ToString('N2', [System.Globalization.CultureInfo]::InvariantCulture)
        $lines.Add(('    {0,-46}{1}{2}' -f $a.Account, $cur, $text))
    }
    $lines.Add(('    {0}' -f $eq))
    $lines.Add("")
    return ($lines -join $nl) + $nl
}

function New-SbAccountsJournal {
    <#
        Declare every account the journals actually use, so 'hledger check accounts'
        is usable. Derived, never hand-maintained, so a new category in a rules file
        cannot break the check.
    #>
    param(
        [Parameter(Mandatory)][string]$Generated,
        [string]$Opening
    )

    $nl = [Environment]::NewLine
    $seen = New-Object System.Collections.Generic.HashSet[string]
    foreach ($p in @($Generated, $Opening)) {
        if (-not $p) { continue }
        foreach ($t in (Get-SbTransactions -Path $p)) {
            foreach ($post in $t.Postings) {
                $parts = $post.Account -split ':'
                for ($i = 1; $i -le $parts.Count; $i++) {
                    [void]$seen.Add(($parts[0..($i-1)] -join ':'))
                }
            }
        }
    }
    $lines = New-Object System.Collections.Generic.List[string]
    $lines.Add("; Generated by SecretBeans - do not edit.")
    $lines.Add("; Every account used by this period's journals, so 'hledger check accounts' passes.")
    $lines.Add("")
    foreach ($a in ($seen | Sort-Object)) { $lines.Add("account $a") }
    $lines.Add("")
    return ($lines -join $nl) + $nl
}

function Get-SbDiagnostics {
    <#
        What to look at before accepting a build.

        Three things matter: transactions hledger could not categorise, transactions
        parked for manual review, and transactions that look like the same event
        imported from two different statements.

        That last one is the expensive mistake. A credit-card payment appears on the
        card statement AND on the bank statement, and unless one side is skipped it is
        recorded twice - inflating the bank outflow and the card credit, while expense
        totals stay innocently correct so nothing looks wrong.
    #>
    param(
        [Parameter(Mandatory)][string]$MainJournal,
        [Parameter(Mandatory)][string]$Hledger,
        [Parameter(Mandatory)]$Config,
        [int]$DuplicateWindowDays = 4
    )

    $txns = Get-SbTransactions -Path $MainJournal
    # main.journal only holds includes, so read what it pulls in
    $dir  = Split-Path -Parent $MainJournal
    $txns = New-Object System.Collections.Generic.List[object]
    foreach ($n in 'opening.journal','generated.journal') {
        foreach ($t in (Get-SbTransactions -Path (Join-Path $dir $n))) { $txns.Add($t) }
    }

    $review = 'expenses:review'
    if ($Config.ContainsKey('ReviewAccount') -and $Config.ReviewAccount) { $review = $Config.ReviewAccount }

    $unknown = New-Object System.Collections.Generic.List[object]
    $toCheck = New-Object System.Collections.Generic.List[object]
    foreach ($t in $txns) {
        foreach ($p in $t.Postings) {
            if ($p.Account -match '(^|:)unknown(:|$)') {
                $unknown.Add([pscustomobject]@{ Date=$t.Date; Description=$t.Description; Account=$p.Account; Amount=$p.Amount; Source=$t.Source })
                break
            }
        }
        foreach ($p in $t.Postings) {
            if ($p.Account.StartsWith($review)) {
                $toCheck.Add([pscustomobject]@{ Date=$t.Date; Description=$t.Description; Account=$p.Account; Amount=$p.Amount; Source=$t.Source })
                break
            }
        }
    }

    # Transfers only: every posting sits in assets/liabilities/equity. An expense or
    # income posting means it is a real purchase, and two identical purchases on the
    # same day are ordinary life, not a duplicate.
    $transfers = New-Object System.Collections.Generic.List[object]
    foreach ($t in $txns) {
        if ($t.Postings.Count -eq 0) { continue }
        $isTransfer = $true
        foreach ($p in $t.Postings) {
            if ($p.Account -notmatch '^(assets|liabilities|equity):') { $isTransfer = $false; break }
        }
        if (-not $isTransfer) { continue }
        $mag = 0.0
        foreach ($p in $t.Postings) { if ($null -ne $p.Amount) { $mag = [Math]::Max($mag, [Math]::Abs($p.Amount)) } }
        if ($mag -gt 0) { $transfers.Add([pscustomobject]@{ Txn=$t; Magnitude=[Math]::Round($mag,2); Source=$t.Source }) }
    }

    $dupes = New-Object System.Collections.Generic.List[object]
    $byAmount = @{}
    foreach ($x in $transfers) {
        $k = [string]$x.Magnitude
        if (-not $byAmount.ContainsKey($k)) { $byAmount[$k] = New-Object System.Collections.Generic.List[object] }
        $byAmount[$k].Add($x)
    }
    foreach ($k in $byAmount.Keys) {
        $group = @($byAmount[$k] | Sort-Object { $_.Txn.Date })
        if ($group.Count -lt 2) { continue }
        for ($i = 0; $i -lt $group.Count - 1; $i++) {
            for ($j = $i + 1; $j -lt $group.Count; $j++) {
                $gap = ($group[$j].Txn.Date - $group[$i].Txn.Date).TotalDays
                if ($gap -gt $DuplicateWindowDays) { break }
                $sameSource = ($group[$i].Source -eq $group[$j].Source)
                $dupes.Add([pscustomobject]@{
                    Amount     = $group[$i].Magnitude
                    DaysApart  = [int]$gap
                    SameSource = $sameSource
                    # Two statements describing one event is the costly bug. One statement
                    # listing the same amount twice is usually two real transactions, so it
                    # is reported but ranked below.
                    Severity   = $(if ($sameSource) { 'Review' } else { 'Likely duplicate' })
                    SourceA    = $group[$i].Source
                    SourceB    = $group[$j].Source
                    A = ('{0:yyyy-MM-dd}  {1}' -f $group[$i].Txn.Date, $group[$i].Txn.Description)
                    B = ('{0:yyyy-MM-dd}  {1}' -f $group[$j].Txn.Date, $group[$j].Txn.Description)
                })
            }
        }
    }

    # Through the helper, so a failing check reports all of what hledger said
    # instead of throwing on its first line of stderr.
    $checkRes = Invoke-SbHledger -Hledger $Hledger -Arguments @('-f', $MainJournal, 'check')
    $checkOut = $checkRes.Text
    $checkOk  = ($checkRes.ExitCode -eq 0)

    $dates = @($txns | ForEach-Object { $_.Date } | Sort-Object)
    $firstDate = $null; $lastDate = $null
    if ($dates.Count -gt 0) { $firstDate = $dates[0]; $lastDate = $dates[$dates.Count-1] }

    # Handed back as plain arrays, not List[object]. Wrapping a List in @() throws
    # 'Argument types do not match' on some PowerShell builds, which is a trap for
    # anything consuming this - the window builds its grid from exactly these two.
    return [pscustomobject]@{
        Transactions   = $txns.Count
        FirstDate      = $firstDate
        LastDate       = $lastDate
        Unknown        = $unknown.ToArray()
        UnknownCount   = $unknown.Count
        Review         = $toCheck.ToArray()
        ReviewCount    = $toCheck.Count
        PossibleDupes  = [object[]]@($dupes | Sort-Object @{Expression={$_.SameSource}}, @{Expression={-$_.Amount}})
        DupeCount      = $dupes.Count
        CrossSourceDupes = @($dupes | Where-Object { -not $_.SameSource }).Count
        CheckPassed    = $checkOk
        CheckOutput    = ($checkOut | Out-String).Trim()
    }
}
